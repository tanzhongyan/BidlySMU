def dash_format_to_acad_term_id(dash: str) -> str:
    """
    Convert dash format (e.g., '2026-27_T1') to BOSS acad_term_id (e.g., 'AY202627T1').

    Usage:
        dash_format_to_acad_term_id('2026-27_T1') -> 'AY202627T1'
    """
    return "AY" + dash.replace('-', '').replace('_', '')


def acad_term_id_to_dash_format(acad_term_id: str) -> str:
    """
    Convert BOSS acad_term_id (e.g., 'AY202627T1') to dash format (e.g., '2026-27_T1').

    Usage:
        acad_term_id_to_dash_format('AY202627T1') -> '2026-27_T1'
    """
    if not acad_term_id or len(acad_term_id) < 9:
        return acad_term_id
    return f"{acad_term_id[2:6]}-{acad_term_id[6:8]}_{acad_term_id[8:]}"


def abbrev_window_to_full(abbrev: str) -> str:
    """
    Convert abbreviated bid window (e.g., 'R1AW2') to full display format
    (e.g., 'Round 1A Window 2'). Returns input unchanged if no match.

    Usage:
        abbrev_window_to_full('R1AW2') -> 'Round 1A Window 2'
        abbrev_window_to_full('R1FW4') -> 'Round 1F Window 4'
        abbrev_window_to_full('R2W1')  -> 'Round 2 Window 1'
    """
    match = re.match(r'^R(\d+)([A-CF]*?)W(\d+)$', abbrev, re.IGNORECASE)
    if not match:
        return abbrev
    rnd = f"Round {match.group(1)}{match.group(2)}"
    win = f"Window {match.group(3)}"
    return f"{rnd} {win}"


def build_window_abbrev(round_str: str, window_num: int) -> str:
    """
    Build abbreviated window key from round and window components.

    Usage:
        build_window_abbrev('1A', 2) -> 'R1AW2'
        build_window_abbrev('1F', 4) -> 'R1FW4'
        build_window_abbrev('2', 1)  -> 'R2W1'
    """
    return f"R{round_str}W{window_num}"


def dash_format_to_display_format(dash: str) -> str:
    """
    Convert dash format (e.g., '2026-27_T1') to BOSS display format
    (e.g., '2026-27 Term 1').

    Usage:
        dash_format_to_display_format('2026-27_T3A') -> '2026-27 Term 3A'
    """
    year_part, term_part = dash.split('_')
    full_term_name = TERM_DISPLAY_MAP.get(term_part, term_part)
    return f"{year_part} {full_term_name}"


def strip_term_prefix(term: str) -> str:
    """
    Strip leading 'T' from term codes.

    Usage:
        strip_term_prefix('T3A') -> '3A'
        strip_term_prefix('T1')  -> '1'
        strip_term_prefix('3A')  -> '3A'  (no-op if no T prefix)
    """
    if term.startswith('T'):
        return term[1:]
    return term


def encode_subterm_for_boss_id(term_code: str) -> str:
    """
    Encode sub-term suffix for BOSS ID construction.
    SMU term structure: T1, T2, T3A, T3B
    Mapping: A -> '1', B -> '2', no suffix -> '0'

    Usage:
        encode_subterm_for_boss_id('3A') -> '1'
        encode_subterm_for_boss_id('3B') -> '2'
        encode_subterm_for_boss_id('1')  -> '0'
    """
    if term_code.endswith('A'):
        return '1'
    elif term_code.endswith('B'):
        return '2'
    return '0'


# Lazy evaluation cache for expensive/time-dependent config values
_config_cache: Dict[str, object] = {}


def _compute_and_cache_window_names() -> None:
    """Compute CURRENT_WINDOW_NAME and PREVIOUS_WINDOW_NAME lazily on first access."""

    def _clean_window_name(entry):
        """Extract clean window name from schedule entry (e.g. 'Round 1A Window 1').

        Uses the abbrev field to produce consistent formatting without BOSS prefix.
        Falls back to raw entry[1] for legacy entries that lack an abbrev.
        """
        if len(entry) >= 3 and entry[2]:
            return abbrev_window_to_full(entry[2])
        return entry[1]  # legacy fallback

    target_current = os.getenv('TARGET_CURRENT_WINDOW')
    target_previous = os.getenv('TARGET_PREVIOUS_WINDOW')
    
    if target_current is not None or target_previous is not None:
        def _parse_target(val):
            if val is None: return None
            if val.lower() == 'none' or val.strip() == '': return None
            return val

        current = _parse_target(target_current)
        previous = _parse_target(target_previous)

        # Fallback: if CURRENT was provided but PREVIOUS wasn't (old schedules
        # that predate the Lambda passing TARGET_PREVIOUS_WINDOW), derive
        # PREVIOUS from bidding_schedules.json by finding the entry before CURRENT.
        if current is not None and previous is None:
            schedule = BIDDING_SCHEDULES.get(START_AY_TERM, [])
            for i, entry in enumerate(schedule):
                if _clean_window_name(entry) == current and i > 0:
                    previous = _clean_window_name(schedule[i - 1])
                    break

        _config_cache['CURRENT_WINDOW_NAME'] = current
        _config_cache['PREVIOUS_WINDOW_NAME'] = previous
        return

    schedule = BIDDING_SCHEDULES.get(START_AY_TERM, [])
    now = datetime.now()

    current_window_name = None
    previous_window_name = None

    for i, entry in enumerate(schedule):
        if now < entry[0]:
            current_window_name = _clean_window_name(entry)
            if i > 0:
                previous_window_name = _clean_window_name(schedule[i - 1])
            break

    if current_window_name is None and schedule:
        current_window_name = None
        previous_window_name = _clean_window_name(schedule[-1])

    _config_cache['CURRENT_WINDOW_NAME'] = current_window_name
    _config_cache['PREVIOUS_WINDOW_NAME'] = previous_window_name


def __getattr__(name):
    """Lazy evaluation for time-dependent and I/O-dependent config values."""
    if name == 'CURRENT_WINDOW_NAME':
        if name not in _config_cache:
            _compute_and_cache_window_names()
        return _config_cache[name]
    if name == 'PREVIOUS_WINDOW_NAME':
        if name not in _config_cache:
            _compute_and_cache_window_names()
        return _config_cache[name]
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def _reset_config_cache() -> None:
    """Clear cached config values. For testing only."""
    _config_cache.clear()


