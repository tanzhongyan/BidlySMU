# Bidding schedules loaded from JSON file (path from env)
# Format: {"2025-26_T1": [["2025-07-09T14:00:00", "Round 1 Window 1", "R1W1",
#                           "2025-07-07T10:00:00", "2025-07-09T10:00:00"], ...]}
# Each entry: [results_at, title, abbrev, opens_at, closes_at]
# Generated by the Lambda scheduler via BossWindow.to_schedule_entry()
def _load_bidding_schedules() -> Dict[str, List[Tuple[datetime, str, str, datetime, datetime]]]:
    """Load bidding schedules from JSON file specified in env."""
    schedules_path = os.getenv('BIDDING_SCHEDULES_PATH', 'script_input/bidding_schedules.json')

    try:
        with open(schedules_path, 'r') as f:
            raw_schedules = json.load(f)

        # Convert JSON format to Python format with datetime objects
        # Entries may have 3 or 5 elements:
        #   Legacy:   [results_at, title, abbrev]
        #   Extended: [results_at, title, abbrev, opens_at, closes_at]
        schedules = {}
        for term, entries in raw_schedules.items():
            parsed = []
            for entry in entries:
                results_at = datetime.fromisoformat(entry[0])
                title = entry[1]
                abbrev = entry[2]
                opens_at = datetime.fromisoformat(entry[3]) if len(entry) >= 5 and entry[3] else None
                closes_at = datetime.fromisoformat(entry[4]) if len(entry) >= 5 and entry[4] else None
                parsed.append((results_at, title, abbrev, opens_at, closes_at))
            schedules[term] = parsed
        return schedules
    except FileNotFoundError:
        print(f"Warning: BIDDING_SCHEDULES_PATH '{schedules_path}' not found. Using empty schedules.")
        return {}
    except Exception as e:
        print(f"Warning: Error loading bidding schedules: {e}. Using empty schedules.")
        return {}

BIDDING_SCHEDULES = _load_bidding_schedules()


