# Term display format mapping for BOSS UI (e.g., 'T3A' -> 'Term 3A')
TERM_DISPLAY_MAP = {
    'T1': 'Term 1',
    'T2': 'Term 2',
    'T3A': 'Term 3A',
    'T3B': 'Term 3B'
}

# Canonical round ordering for sorting bid windows.
# Keys are WITHOUT the "R" prefix (matching parse_bidding_window output).
ROUND_ORDER: Dict[str, int] = {
    '1': 1, '1A': 2, '1B': 3, '1C': 4, '1F': 5, '2': 6, '2A': 7,
}

def acad_term_id_to_display_format(acad_term_id: str) -> str:
    """
    Convert ACAD_TERM_ID (e.g., 'AY202526T3A') to display format (e.g., '2025-26 Term 3A').

    Usage:
        acad_term_id_to_display_format('AY202526T3A') -> '2025-26 Term 3A'
    """
    if not acad_term_id or len(acad_term_id) < 9:
        return acad_term_id
    start_year = acad_term_id[2:6]
    end_year = acad_term_id[6:8]
    term_code = acad_term_id[8:]
    display_term = TERM_DISPLAY_MAP.get(term_code, term_code)
    return f"{start_year}-{end_year} {display_term}"


def abbrev_window_to_full(abbrev: str) -> str:
    """
    Convert abbreviated bid window (e.g., 'R1AW2') to full display format
    (e.g., 'Round 1A Window 2'). Returns input unchanged if no match.

    Usage:
        abbrev_window_to_full('R1AW2') -> 'Round 1A Window 2'
        abbrev_window_to_full('R1FW4') -> 'Round 1F Window 4'
        abbrev_window_to_full('R2W1')  -> 'Round 2 Window 1'
    """
    match = re.match(r'^R(\d+)([A-CF]*?)W(\d+)$', abbrev, re.IGNORECASE)
    if not match:
        return abbrev
    rnd = f"Round {match.group(1)}{match.group(2)}"
    win = f"Window {match.group(3)}"
    return f"{rnd} {win}"


def build_window_abbrev(round_str: str, window_num: int) -> str:
    """
    Build abbreviated window key from round and window components.

    Usage:
        build_window_abbrev('1A', 2) -> 'R1AW2'
        build_window_abbrev('1F', 4) -> 'R1FW4'
        build_window_abbrev('2', 1)  -> 'R2W1'
    """
    return f"R{round_str}W{window_num}"


def strip_term_prefix(term: str) -> str:
    """
    Strip leading 'T' from term codes.

    Usage:
        strip_term_prefix('T3A') -> '3A'
        strip_term_prefix('T1')  -> '1'
        strip_term_prefix('3A')  -> '3A'  (no-op if no T prefix)
    """
    if term.startswith('T'):
        return term[1:]
    return term


def encode_subterm_for_boss_id(term_code: str) -> str:
    """
    Encode sub-term suffix for BOSS ID construction.
    SMU term structure: T1, T2, T3A, T3B
    Mapping: A -> '1', B -> '2', no suffix -> '0'

    Usage:
        encode_subterm_for_boss_id('3A') -> '1'
        encode_subterm_for_boss_id('3B') -> '2'
        encode_subterm_for_boss_id('1')  -> '0'
    """
    if term_code.endswith('A'):
        return '1'
    elif term_code.endswith('B'):
        return '2'
    return '0'


def acad_term_id_to_short(acad_term_id: str) -> str:
    """Convert AY term (e.g. 'AY202627T1') to the BOSS ClassDetails URL code (e.g. '2610').

    Format: last 2 digits of start year + term digit + subterm code
      Term 1/2 -> trailing 0 (e.g. '2610', '2520')
      Term 3A  -> trailing 1 (e.g. '2531')
      Term 3B  -> trailing 2 (e.g. '2532')
    """
    if not acad_term_id or len(acad_term_id) < 9:
        return acad_term_id
    start_yy = f"{int(acad_term_id[2:6]) % 100:02d}"
    term_raw = acad_term_id[8:]
    term_code = term_raw[1:] if term_raw.startswith('T') else term_raw
    term_num = term_code[0]
    sub = '1' if term_code.endswith('A') else '2' if term_code.endswith('B') else '0'
    return f"{start_yy}{term_num}{sub}"


