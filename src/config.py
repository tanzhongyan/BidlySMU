# Bidding schedules — loaded from Supabase Storage (canonical source of truth).
# Format: {"AY202627T1": [["2025-07-09T14:00:00", "Round 1 Window 1", "R1W1",
#                           "2025-07-07T10:00:00", "2025-07-09T10:00:00"], ...]}
# Each entry: [results_at, title, abbrev, opens_at, closes_at]
# Generated by the monthly scheduler Lambda and stored at
# schedules/bidding_schedules.json in the bidlysmu-files bucket.
def _parse_sgt(s: str) -> datetime:
    """Parse an ISO 8601 timestamp and pin it to SGT (UTC+8).

    Naive timestamps (as returned by the live Trumba API, which already uses
    SGT wall-clock) are treated as SGT. Aware timestamps are converted to SGT.
    Handles Python < 3.11 where datetime.fromisoformat rejects a trailing 'Z'.
    """
    if not s:
        raise ValueError("empty timestamp")
    if s[-1] in 'Zz':
        s = s[:-1] + '+00:00'
    dt = datetime.fromisoformat(s)
    if dt.tzinfo is None:
        return dt.replace(tzinfo=SGT)
    return dt.astimezone(SGT)


def to_sgt_aware(dt: datetime) -> datetime:
    """Interpret a (possibly naive) datetime as SGT and return it SGT-aware.

    Naive datetimes are treated as SGT wall-clock (the schedule convention);
    aware datetimes are converted to SGT.
    """
    if dt.tzinfo:
        return dt.astimezone(SGT)
    return dt.replace(tzinfo=SGT)


def to_utc_str(dt: datetime) -> str:
    """Format a datetime as an EventBridge ``at()`` UTC timestamp.

    Naive datetimes are treated as SGT wall-clock (the schedule convention),
    then converted to UTC. EventBridge interprets naive at() timestamps as
    UTC, so the SGT->UTC conversion must happen here — never use hardcoded
    -8h arithmetic.
    """
    return to_sgt_aware(dt).astimezone(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S')


# ============================================================================
# TIMEZONE CONVENTION
# ============================================================================
# In-memory schedule datetimes are SGT-aware (tzinfo=SGT, UTC+8).
# bidding_schedules.json stores naive SGT wall-clock strings.
# Postgres TIMESTAMPTZ columns store UTC internally (SGT-aware writes
# normalize to UTC at write time).
# EventBridge at() schedules require UTC — convert SGT -> UTC at that
# boundary only, via to_utc_str().
def _parse_schedule_entries(raw_schedules: dict) -> Dict[str, List[Tuple[datetime, str, str, datetime, datetime]]]:
    """Convert raw JSON schedule entries into SGT-aware datetime tuples.

    Canonical entry format (written by the scheduler Lambda):
        [results_at, title, abbrev, opens_at, closes_at]
    opens_at/closes_at may be null; a single malformed entry is skipped
    (logged) rather than discarding the whole schedule file.
    """
    logger = get_logger(__name__)
    schedules: Dict[str, List[Tuple[datetime, str, str, datetime, datetime]]] = {}
    for term, entries in raw_schedules.items():
        parsed = []
        for i, entry in enumerate(entries):
            try:
                if not isinstance(entry, (list, tuple)) or len(entry) != 5:
                    raise ValueError(f"expected 5-element entry, got {entry!r}")
                results_at = _parse_sgt(entry[0])
                title = entry[1]
                abbrev = entry[2]
                opens_at = _parse_sgt(entry[3]) if entry[3] else None
                closes_at = _parse_sgt(entry[4]) if entry[4] else None
                parsed.append((results_at, title, abbrev, opens_at, closes_at))
            except Exception as e:
                logger.warning(f"Skipping malformed bidding schedule entry for {term} (index {i}): {e}")
                continue
        schedules[term] = parsed
    return schedules


def _load_bidding_schedules() -> Dict[str, List[Tuple[datetime, str, str, datetime, datetime]]]:
    """Load bidding schedules from Supabase Storage (schedules/bidding_schedules.json).

    The scheduler Lambda is the sole writer of this file; it is guaranteed to
    exist at this path.
    """
    logger = get_logger(__name__)
    try:
        from supabase import create_client
        supabase = create_client(SUPABASE_URL, SUPABASE_SERVICE_KEY)
        response = supabase.storage.from_("bidlysmu-files").download(
            "schedules/bidding_schedules.json"
        )
        raw_schedules = json.loads(response.decode('utf-8'))
        logger.info("Loaded bidding schedules from Supabase Storage.")
        return _parse_schedule_entries(raw_schedules)
    except Exception as e:
        logger.warning(
            f"Could not load bidding schedules from Supabase Storage: {e}. "
            "Using empty schedules."
        )
        return {}

BIDDING_SCHEDULES = _load_bidding_schedules()


